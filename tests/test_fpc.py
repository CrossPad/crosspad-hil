# --------------------------------------------------------------------------- CLI

def _deps() -> tuple[cli.CliDeps, io.StringIO, io.StringIO]:
    """CLI deps with no device backends — neither verb may look for a board."""
    out, err = io.StringIO(), io.StringIO()
    deps = cli.CliDeps(backends=Backends(list_serial=list, list_midi=list, list_audio=list),
                       stdout=out, stderr=err)
    return deps, out, err


def test_cli_to_fpc_then_from_fpc(kit_dir: Path, tmp_path: Path) -> None:
    prefix_root = tmp_path / "drive_c"
    win_dir = prefix_root / "users/me/Documents/CrossPad/TEST_KIT/SAMPLES"
    win_dir.mkdir(parents=True)
    for wav in (kit_dir / "SAMPLES").glob("*.wav"):
        (win_dir / wav.name).write_bytes(wav.read_bytes())

    deps, out, _ = _deps()
    fst = tmp_path / "cli.fst"
    rc = cli.main(["kit", "to-fpc", str(kit_dir), str(fst),
                   "--win-prefix", r"C:\users\me\Documents\CrossPad\TEST_KIT"], deps=deps)
    assert rc == 0 and fst.is_file()

    deps, out, _ = _deps()
    rc = cli.main(["--json", "kit", "from-fpc", str(fst), str(tmp_path / "cliout"),
                   "--drive-c", str(prefix_root)], deps=deps)
    assert rc == 0
    result = json.loads(out.getvalue())
    assert result["samples"] == 4
    assert Path(result["dir"], "kit.json").is_file()


def test_cli_from_fpc_rejects_a_missing_preset(tmp_path: Path) -> None:
    deps, _, _ = _deps()
    assert cli.main(["kit", "from-fpc", str(tmp_path / "nope.fst"), str(tmp_path)],
                    deps=deps) != 0
