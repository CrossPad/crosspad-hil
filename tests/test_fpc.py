def test_colour_swaps_between_fl_and_crosspad_byte_order() -> None:
    pad = fpc.FpcPad(index=0, params=[0] * 16)
    pad.params[fpc._P_COLOR] = 0x0000A19145        # FL: 0x00BBGGRR
    assert pad.color == 0x4591A1                   # CrossPad: 0xRRGGBB


def test_empty_pads_get_the_fpc_default_note_map(kit_dir: Path, tmp_path: Path) -> None:
    preset = fpc.parse_fpc_preset(fpc.fpc_from_kit(kit_dir, tmp_path / "notes.fst"))
    # build_kit pads the kit to 16 entries; every kit pad lands on the note
    # DAW Control plays for it, bank B keeps FPC's own defaults.
    assert [p.note for p in preset.pads[:16]] == [fpc.DAW_BASE_NOTE + i for i in range(16)]
    assert [p.note for p in preset.pads[16:]] == list(fpc.FPC_DEFAULT_NOTES[16:])
    assert preset.pads[16].sample_path == ""


def test_playing_layer_is_the_one_a_full_strength_hit_reaches() -> None:
    def layer(path: str, low: int, high: int) -> fpc.FpcLayer:
        return fpc.FpcLayer(sample_path=path, params=[127, 0, low, high, 1, 0, -1])

    pad = fpc.FpcPad(index=0, layers=[layer("soft.wav", 0, 63), layer("hard.wav", 64, 127)])
    assert pad.sample_path == "hard.wav"
    pad.layers = [layer("only.wav", 0, 40)]        # nothing covers 127: the last one wins
    assert pad.sample_path == "only.wav"
    pad.layers = [fpc.FpcLayer()]
    assert pad.playing_layer() is None


def test_choke_group_reports_zero_for_fpcs_no_group() -> None:
    params = [0] * 16
    params[fpc._P_CUT] = -1
    assert fpc.FpcPad(index=0, params=params).choke_group == 0
    params[fpc._P_CUT] = 3
    assert fpc.FpcPad(index=0, params=params).choke_group == 3


