def _wav(path: Path, freq: float, *, rate: int = 44100, seconds: float = 0.03) -> None:
    n = int(rate * seconds)
    frames = [(int(12000 * math.sin(2 * math.pi * freq * i / rate)),) * 2 for i in range(n)]
    kits.write_stereo16_wav(path, frames, rate)


