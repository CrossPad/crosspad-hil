def test_parse_write_is_byte_identical(preset_path: Path, tmp_path: Path) -> None:
    preset = fpc.parse_fpc_preset(preset_path)
    again = fpc.write_fpc_preset(preset, tmp_path / "again.fst")
    assert again.read_bytes() == preset_path.read_bytes()


@pytest.mark.parametrize("path", _factory_presets(),
                         ids=lambda p: p.stem)
def test_factory_preset_parses_and_rewrites_byte_identical(path: Path, tmp_path: Path) -> None:
    """The strongest compatibility check available without running FL itself.

    If the writer reproduces FL's own bytes for every factory preset, then the
    container, the event stream and the whole record tree are being emitted the
    way FL wrote them — only the *content* of a preset built from a kit is new.
    """
    preset = fpc.parse_fpc_preset(path)
    assert len(preset.pads) == fpc.FPC_PAD_COUNT
    out = fpc.write_fpc_preset(preset, tmp_path / "rewritten.fst")
    assert out.read_bytes() == path.read_bytes()


@pytest.mark.skipif(not _factory_presets(), reason="no FL Studio Wine prefix on this machine")
def test_factory_preset_pads_carry_names_notes_and_samples() -> None:
    presets = {p.stem: p for p in _factory_presets()}
    path = presets.get("808") or next(iter(presets.values()))
    preset = fpc.parse_fpc_preset(path)
    pads = preset.bank(0)
    assert len(pads) == fpc.FPC_BANK_PADS
    assert any(pad.name for pad in pads)
    assert any(pad.sample_path.lower().endswith(".wav") for pad in pads)
    assert all(0 <= pad.note < 128 for pad in preset.pads)


def test_kit_to_preset_to_kit_preserves_pad_fields(kit_dir: Path, tmp_path: Path) -> None:
    """The full loop, with the WAVs put where the preset's Windows paths point."""
    prefix_root = tmp_path / "drive_c"
    win_dir = prefix_root / "users/me/Documents/CrossPad/TEST_KIT"
    (win_dir / "SAMPLES").mkdir(parents=True)
    for wav in (kit_dir / "SAMPLES").glob("*.wav"):
        (win_dir / "SAMPLES" / wav.name).write_bytes(wav.read_bytes())

    fst = fpc.fpc_from_kit(kit_dir, tmp_path / "loop.fst",
                           win_prefix=r"C:\users\me\Documents\CrossPad\TEST_KIT")
    back = fpc.kit_from_fpc(fpc.parse_fpc_preset(fst), tmp_path / "back", drive_c=prefix_root)

    before = json.loads((kit_dir / "kit.json").read_text())["pads"]
    after = json.loads((back / "kit.json").read_text())["pads"]
    assert len(after) == kits.MAX_PADS
    for a, b in zip(before, after, strict=True):
        assert (a["color"], a["volume"], a["pan"]) == (b["color"], b["volume"], b["pan"])
        assert len(a["samples"]) == len(b["samples"])
    for wav in (back / "SAMPLES").glob("*.wav"):
        assert wav.read_bytes() == (kit_dir / "SAMPLES" / wav.name).read_bytes()


def test_pad_names_survive_the_loop(kit_dir: Path, tmp_path: Path) -> None:
    kit_json = kit_dir / "kit.json"
    kit = json.loads(kit_json.read_text())
    kit["pads"][0]["name"] = "Kick Drum"
    kit["pads"][1]["note"] = 36
    kit_json.write_text(json.dumps(kit))

    preset = fpc.parse_fpc_preset(fpc.fpc_from_kit(kit_dir, tmp_path / "named.fst"))
    assert preset.pads[0].name == "Kick Drum"
    assert preset.pads[1].note == 36


