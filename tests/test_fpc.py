# --------------------------------------------------------------------------- container

def test_written_preset_has_the_flhd_fldt_container(preset_path: Path) -> None:
    data = preset_path.read_bytes()
    assert data[:4] == fpc.FLHD
    header_len = struct.unpack_from("<I", data, 4)[0]
    assert data[8:8 + header_len] == fpc.FLHD_PAYLOAD
    off = 8 + header_len
    assert data[off:off + 4] == fpc.FLDT
    body_len = struct.unpack_from("<I", data, off + 4)[0]
    # The chunk length has to account for every byte after it, or FL stops early.
    assert off + 8 + body_len == len(data)


def test_written_preset_has_the_factory_event_sequence(preset_path: Path) -> None:
    preset = fpc.parse_fpc_preset(preset_path)
    ids = [ev for ev, _ in preset.events]
    assert ids == [ev for ev, _ in fpc.TEMPLATE_EVENTS]
    assert dict(preset.events)[fpc.EV_PLUGIN_NAME] == "FPC\0".encode("utf-16-le")


def test_written_preset_has_thirty_two_pads_and_the_three_globals(preset_path: Path) -> None:
    preset = fpc.parse_fpc_preset(preset_path)
    assert len(preset.pads) == fpc.FPC_PAD_COUNT
    assert [rec_id for rec_id, _ in preset.globals_] == [rec_id for rec_id, _
                                                         in fpc.DEFAULT_GLOBALS]


def test_parse_rejects_a_file_that_is_not_an_fst(tmp_path: Path) -> None:
    junk = tmp_path / "junk.fst"
    junk.write_bytes(b"not an FL file at all")
    with pytest.raises(HilError) as exc:
        fpc.parse_fpc_preset(junk)
    assert exc.value.code == BAD_ARGS


def test_parse_rejects_a_preset_for_another_plugin(preset_path: Path, tmp_path: Path) -> None:
    preset = fpc.parse_fpc_preset(preset_path)
    preset.events = [(ev, "Sytrus\0".encode("utf-16-le") if ev == fpc.EV_PLUGIN_NAME else raw)
                     for ev, raw in preset.events]
    other = fpc.write_fpc_preset(preset, tmp_path / "sytrus.fst")
    with pytest.raises(HilError, match="not FPC"):
        fpc.parse_fpc_preset(other)


